import { bahtText } from './bahttext.js';

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [1250.5, 'หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์'],
    [77040, 'เจ็ดหมื่นเจ็ดพันสี่สิบบาทถ้วน'],
    [1_000_000, 'หนึ่งล้านบาทถ้วน'],
    [21_000_001, 'ยี่สิบเอ็ดล้านเอ็ดบาทถ้วน'],
    [0.25, 'ยี่สิบห้าสตางค์'],
  ])('%s', (n, expected) => {
    expect(bahtText(n)).toBe(expected);
  });
});
